/**
 * Generate the app's design foundation from the design system (BUILD.md §7.0):
 *
 *   src/styles/tokens.css       <- design/tokens.json  (light `:root`, dark via data-theme or prefers-color-scheme)
 *   src/styles/components.css   <- design/components/bundle.css  WITHOUT the doc-* mockup rules and the font @import
 *   src/lib/icons.generated.ts  <- ICONS of design/components/bundle.js (24px line-icon sprite, `i-<name>` symbols)
 *
 *   npx tsx scripts/build-design.ts [--check]     (--check fails if the committed output is stale)
 */
import { existsSync } from "node:fs";
import { cp, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import vm from "node:vm";
import postcss, { type AnyNode, type Container, type Rule } from "postcss";

interface ColorToken { name: string; value: string | { light: string; dark: string } }
interface ValueToken { name: string; value: string | { light: string; dark: string } }
interface TypeStyle { name: string; fontSize: string; lineHeight: string; fontWeight: number; letterSpacing?: string }
interface Tokens {
  color: { tokens: ColorToken[] };
  type: { families: Record<string, string>; groups: { styles: TypeStyle[] }[] };
  spacing: { tokens: ValueToken[] };
  radius: { tokens: ValueToken[] };
  shadow: { tokens: ValueToken[] };
  tilt: { tokens: ValueToken[] };
  size: { tokens: ValueToken[] };
  zIndex: { tokens: ValueToken[] };
}

const check = process.argv.includes("--check");
const outputs = new Map<string, string>();

// ── tokens.css ────────────────────────────────────────────────────────────
const tokens = JSON.parse(await readFile("design/tokens.json", "utf8")) as Tokens;

/** `{brand}` references become `var(--brand)`. */
const resolve = (v: string) => v.replace(/\{([a-z0-9-]+)\}/g, "var(--$1)");

const shared: string[] = [];
const light: string[] = [];
const dark: string[] = [];
const add = (t: ValueToken | ColorToken) => {
  if (typeof t.value === "string") shared.push(`  --${t.name}: ${resolve(t.value)};`);
  else {
    light.push(`  --${t.name}: ${resolve(t.value.light)};`);
    dark.push(`  --${t.name}: ${resolve(t.value.dark)};`);
  }
};
[...tokens.color.tokens, ...tokens.shadow.tokens, ...tokens.spacing.tokens, ...tokens.radius.tokens,
  ...tokens.tilt.tokens, ...tokens.size.tokens, ...tokens.zIndex.tokens].forEach(add);

// The design system names the families by their Google Fonts names. The app self-hosts the same fonts
// (@fontsource-variable), whose family names carry a " Variable" suffix, so list both.
const family = (v: string) =>
  v.replace('"Bricolage Grotesque"', '"Bricolage Grotesque Variable", "Bricolage Grotesque"')
    .replace(/(^|,\s*)Figtree,/, '$1"Figtree Variable", Figtree,');
for (const [name, value] of Object.entries(tokens.type.families)) {
  shared.push(`  --font-${name}: ${family(value)};`);
}
for (const style of tokens.type.groups.flatMap((g) => g.styles)) {
  shared.push(`  --fs-${style.name}: ${style.fontSize};`, `  --lh-${style.name}: ${style.lineHeight};`, `  --fw-${style.name}: ${style.fontWeight};`);
  if (style.letterSpacing) shared.push(`  --ls-${style.name}: ${style.letterSpacing};`);
}

outputs.set(
  "src/styles/tokens.css",
  [
    "/* GENERATED by scripts/build-design.ts from design/tokens.json. Do not edit. */",
    `:root {\n  color-scheme: light dark;\n${shared.join("\n")}\n${light.join("\n")}\n}`,
    `:root[data-theme="light"] { color-scheme: light; }`,
    `:root[data-theme="dark"] {\n  color-scheme: dark;\n${dark.join("\n")}\n}`,
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${dark.join("\n").replace(/^/gm, "  ")}\n  }\n}`,
    "",
  ].join("\n\n"),
);

// ── components.css (bundle.css minus doc-* and the font @import) ───────────
const isDocSelector = (s: string) => /\.doc-/.test(s);

function prune(container: Container): void {
  container.each((node: AnyNode) => {
    if (node.type === "rule") {
      const rule = node as Rule;
      const kept = rule.selectors.filter((s) => !isDocSelector(s));
      if (kept.length === 0) rule.remove();
      else if (kept.length !== rule.selectors.length) rule.selectors = kept;
    } else if (node.type === "atrule") {
      if (node.name === "import") node.remove();
      else if (node.nodes) {
        prune(node);
        if (node.nodes.length === 0) node.remove();
      }
    }
  });
}

const bundle = postcss.parse(await readFile("design/components/bundle.css", "utf8"));
prune(bundle);
// Drop the comment section that only announces the removed docs canvas.
bundle.walkComments((c) => { if (/docs canvas/i.test(c.text) && /not for the app/i.test(c.text) && !c.text.includes("Sections:")) c.remove(); });
outputs.set(
  "src/styles/components.css",
  `/* GENERATED by scripts/build-design.ts from design/components/bundle.css (doc-* rules and font @import removed). Do not edit. */\n${bundle.toString().trim()}\n`,
);

// ── icons ─────────────────────────────────────────────────────────────────
const js = await readFile("design/components/bundle.js", "utf8");
const m = /var ICONS = (\{[\s\S]*?\n  \});/.exec(js);
if (!m) throw new Error("could not locate ICONS in bundle.js");
const icons = vm.runInNewContext(`(${m[1]})`) as Record<string, string>;
const body = Object.entries(icons).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
outputs.set(
  "src/lib/icons.generated.ts",
  `// GENERATED by scripts/build-design.ts from design/components/bundle.js. Do not edit.\nexport const ICONS = {\n${body}\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n`,
);

// ── flags (flag-icons 4x3 SVGs -> src/public/flags/<cc>.svg, served as static assets) ──────────────
if (!check) {
  await mkdir("src/public/flags", { recursive: true });
  await cp("node_modules/flag-icons/flags/4x3", "src/public/flags", { recursive: true });
  console.log("copied flag-icons SVGs to src/public/flags");
}

// ── write / check ─────────────────────────────────────────────────────────
let stale = false;
for (const [path, content] of outputs) {
  const current = existsSync(path) ? await readFile(path, "utf8") : null;
  if (check) {
    if (current !== content) { console.error(`stale: ${path}`); stale = true; }
    continue;
  }
  await mkdir(dirname(path), { recursive: true });
  if (current !== content) await writeFile(path, content);
  console.log(`${current === content ? "unchanged" : "wrote"} ${path} (${content.length} bytes)`);
}
if (stale) process.exit(1);

const leftover = (outputs.get("src/styles/components.css") ?? "").match(/\.doc-/g)?.length ?? 0;
if (leftover) throw new Error(`${leftover} doc-* selectors survived`);
